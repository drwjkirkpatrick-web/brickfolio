"""Import Rebrickable's public CSV downloads into the catalog tables.

Rebrickable publishes its whole LEGO catalog as plain CSV files
(colors.csv, parts.csv, sets.csv, ...). This module copies them into the
SQLite tables defined in ``brickfolio.db``, giving brickfolio an
offline, joinable copy of the canonical part/color/set data.

Key behaviours (see PROMPTS.md, Prompt 2):
- Import order follows ``db.CATALOG_TABLES`` — parents strictly before
  the tables that reference them, so FK enforcement never rejects a row
  that merely appears "too early" in a naive directory listing.
- ``INSERT OR REPLACE`` makes the importer idempotent: re-running it
  against the same files leaves the catalog unchanged.
- Bad rows never abort a file: malformed rows and FK violations are
  skipped, counted in the ImportReport, and reported with exactly one
  stderr warning per affected file.
- A missing file is noted in the report and skipped; the import keeps
  going (a partial catalog is useful, and re-running after adding the
  file fills the gap).
"""

import csv
import sqlite3
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from .db import CATALOG_TABLES, Database

__all__ = ["ImportReport", "import_catalog"]


@dataclass(frozen=True)
class ImportReport:
    """Summary of one ``import_catalog`` run.

    Invariants: ``rows + skipped`` == every data row seen in the imported
    files, and ``files + len(notes)`` == every expected file (each
    missing file becomes exactly one note).
    """

    files: int
    rows: int
    skipped: int
    notes: tuple[str, ...] = ()


class _RowError(ValueError):
    """Raised when a single CSV row cannot be converted (internal)."""


# ---- per-column converters ----------------------------------------------
# WHY converter factories instead of bespoke parsing code per table: one
# place defines what "malformed" means, and adding a column to a table
# spec below is a one-line change.


def _text(required: bool = False, default: str = "") -> Callable[[str], str]:
    """TEXT column: stripped value; empty cell → default (malformed if required)."""

    def convert(raw: str) -> str:
        value = raw.strip()
        if not value:
            if required:
                raise _RowError("empty required text field")
            return default
        return value

    return convert


def _int(required: bool = False, default: int | None = None) -> Callable[[str], int | None]:
    # NOTE: `default` also covers NOT NULL columns with schema defaults
    # (e.g. inventories.version defaults to 1) — an empty cell means
    # "let the schema default apply", not "store NULL".
    def convert(raw: str) -> int | None:
        value = raw.strip()
        if not value:
            if required:
                raise _RowError("empty required integer field")
            return default
        try:
            return int(value)
        except ValueError:
            raise _RowError(f"not an integer: {value!r}") from None

    return convert


_TRUTHY = {"t", "true", "1", "yes", "y"}
_FALSY = {"f", "false", "0", "no", "n"}


def _flag(default: int = 0) -> Callable[[str], int]:
    # WHY accept several spellings: Rebrickable ships "t"/"f", but the
    # CSVs get regenerated by third parties and "True"/"1" appear in the
    # wild. Unknown junk (e.g. "maybe") is malformed, not silently false.
    def convert(raw: str) -> int:
        value = raw.strip().lower()
        if not value:
            return default
        if value in _TRUTHY:
            return 1
        if value in _FALSY:
            return 0
        raise _RowError(f"not a boolean flag: {value!r}")

    return convert


@dataclass(frozen=True)
class _TableSpec:
    """One catalog table: its CSV filename and per-column converters.

    NOTE: converter order == CSV column order == schema column order
    (Rebrickable's canonical layout), so parsing is purely positional;
    the header line is skipped, never interpreted.
    """

    table: str
    filename: str
    converters: tuple[tuple[str, Callable[[str], object]], ...]

    @property
    def columns(self) -> tuple[str, ...]:
        return tuple(name for name, _ in self.converters)

    def convert(self, raw_row: list[str]) -> tuple:
        if len(raw_row) != len(self.converters):
            raise _RowError(
                f"expected {len(self.converters)} fields, got {len(raw_row)}"
            )
        return tuple(
            convert(field) for (_, convert), field in zip(self.converters, raw_row)
        )


# NOTE: converter defaults mirror the schema defaults in db.py (rgb
# '000000', is_trans/is_spare 0, inventories.version 1) so an empty CSV
# cell produces the same row the schema would build itself.
_SPECS = {
    "part_categories": _TableSpec(
        "part_categories",
        "part_categories.csv",
        (("id", _int(required=True)), ("name", _text(required=True))),
    ),
    "themes": _TableSpec(
        "themes",
        "themes.csv",
        (
            ("id", _int(required=True)),
            ("name", _text(required=True)),
            ("parent_id", _int()),
        ),
    ),
    "colors": _TableSpec(
        "colors",
        "colors.csv",
        (
            ("id", _text(required=True)),
            ("name", _text(required=True)),
            ("rgb", _text(default="000000")),
            ("is_trans", _flag()),
        ),
    ),
    "parts": _TableSpec(
        "parts",
        "parts.csv",
        (
            ("part_num", _text(required=True)),
            ("name", _text(required=True)),
            ("part_cat_id", _int()),
        ),
    ),
    "sets": _TableSpec(
        "sets",
        "sets.csv",
        (
            ("set_num", _text(required=True)),
            ("name", _text(required=True)),
            ("year", _int()),
            ("theme_id", _int()),
            ("num_parts", _int()),
        ),
    ),
    "inventories": _TableSpec(
        "inventories",
        "inventories.csv",
        (
            ("id", _int(required=True)),
            ("set_num", _text(required=True)),
            ("version", _int(default=1)),
        ),
    ),
    "inventory_parts": _TableSpec(
        "inventory_parts",
        "inventory_parts.csv",
        (
            ("inventory_id", _int(required=True)),
            ("part_num", _text(required=True)),
            ("color_id", _text(required=True)),
            ("quantity", _int(required=True)),
            ("is_spare", _flag()),
        ),
    ),
}

if set(_SPECS) != set(CATALOG_TABLES):
    # WHY fail at import time: db.py owns the FK-safe order; a table
    # added there without a spec here (or vice versa) is a programmer
    # error that must surface before any import runs.
    raise RuntimeError(
        "importer table specs out of sync with db.CATALOG_TABLES: "
        + ", ".join(sorted(set(_SPECS) ^ set(CATALOG_TABLES)))
    )


def import_catalog(db: Database, csv_dir: str | Path) -> ImportReport:
    """Load every Rebrickable CSV found in ``csv_dir`` into ``db``.

    Returns an ImportReport and never raises for per-file problems:
    missing files become notes, malformed/FK-violating rows are skipped
    and counted. (A present-but-unreadable file still raises — that is
    an environment failure the caller should see, not catalog data.)
    """
    csv_dir = Path(csv_dir)
    files = rows = skipped = 0
    notes: list[str] = []

    for table in CATALOG_TABLES:  # WHY: FK-safe order, single source of truth
        spec = _SPECS[table]
        path = csv_dir / spec.filename
        if not path.is_file():
            notes.append(f"missing file: {spec.filename}")
            continue
        inserted, bad = _import_file(db, path, spec)
        files += 1
        rows += inserted
        skipped += bad
        if bad:
            # NOTE: exactly one warning per file, not per row — the real
            # inventory_parts.csv has millions of rows, so per-row
            # warnings would flood stderr (counts live in the report).
            print(
                f"warning: {spec.filename}: skipped {bad} malformed or "
                "constraint-violating row(s)",
                file=sys.stderr,
            )

    return ImportReport(
        files=files, rows=rows, skipped=skipped, notes=tuple(notes)
    )


def _import_file(db: Database, path: Path, spec: _TableSpec) -> tuple[int, int]:
    """Insert one CSV file's rows into its table; return (inserted, skipped)."""
    # NOTE: table/column names come from the trusted _SPECS constants,
    # never from the CSV, so f-string interpolation here is safe.
    columns = ", ".join(spec.columns)
    placeholders = ", ".join("?" * len(spec.converters))
    sql = f"INSERT OR REPLACE INTO {spec.table} ({columns}) VALUES ({placeholders})"

    inserted = skipped = 0
    # WHY utf-8-sig: reads plain UTF-8 unchanged but also strips a BOM
    # if one snuck in during download/unpacking.
    with open(path, newline="", encoding="utf-8-sig") as handle:
        reader = csv.reader(handle)
        next(reader, None)  # NOTE: first line is a header — skip, don't parse.
        for raw_row in reader:
            if not raw_row:  # blank line — noise, not data
                continue
            try:
                values = spec.convert(raw_row)
            except _RowError:
                skipped += 1
                continue
            try:
                db.conn.execute(sql, values)
            except sqlite3.IntegrityError:
                # WHY IntegrityError only: Database runs with
                # PRAGMA foreign_keys = ON, so rows referencing a missing
                # parent land here — a data problem worth skipping. Other
                # sqlite errors (bad SQL, locked db) are code/environment
                # bugs and must propagate loudly.
                skipped += 1
                continue
            inserted += 1
    db.conn.commit()
    return inserted, skipped